export async function listCustomers(search = '') {
  if (!pool) {
    const query = search.trim().toLocaleLowerCase('vi');
    return memory.users
      .filter((user) => user.role === 'user'
        && (!query || `${user.name} ${user.email} ${user.phone ?? ''}`.toLocaleLowerCase('vi').includes(query)))
      .map((user) => ({
        id: user.id,
        name: user.name,
        email: user.email,
        phone: user.phone ?? '',
        address: user.address ?? '',
        createdAt: mapUser(user).createdAt,
        orderCount: memory.orders.filter((order) => order.userId === user.id).length
      }))
      .sort((left, right) => left.name.localeCompare(right.name, 'vi'));
  }
  const result = await pool.query(
    `SELECT u.id, u.name, u.email, u.role, u.phone, u.address, u.created_at,
      COUNT(o.id)::INTEGER AS order_count
     FROM users u LEFT JOIN orders o ON o.user_id = u.id
     WHERE u.role = 'user'
       AND ($1 = '' OR u.name ILIKE $2 OR u.email ILIKE $2 OR u.phone ILIKE $2)
     GROUP BY u.id
     ORDER BY u.created_at DESC`,
    [search.trim(), `%${search.trim()}%`]
  );
  return result.rows.map((row) => ({
    id: Number(row.id),
    name: row.name,
    email: row.email,
    phone: row.phone,
    address: row.address,
    createdAt: new Date(row.created_at).toLocaleString('vi-VN'),
    orderCount: Number(row.order_count)
  }));
}

export async function getAccountBenefits(userId) {
  if (!pool) {
    return {
      vouchers: memory.vouchers.filter((voucher) => voucher.userId === userId && new Date(voucher.expiresAt) > new Date()),
      notifications: memory.notifications.filter((notification) => notification.userId === userId)
    };
  }
  const [vouchers, notifications] = await Promise.all([
    pool.query(
      `SELECT code, title, description, discount_percent AS "discountPercent",
        expires_at AS "expiresAt", used_at AS "usedAt"
       FROM vouchers WHERE user_id = $1 AND expires_at > NOW()
       ORDER BY expires_at`,
      [userId]
    ),
    pool.query(
      `SELECT id, title, message, created_at AS "createdAt", read_at AS "readAt"
       FROM notifications WHERE user_id = $1 ORDER BY created_at DESC`,
      [userId]
    )
  ]);
  return { vouchers: vouchers.rows, notifications: notifications.rows };
}

export async function markAccountNotificationRead(userId, notificationId) {
  if (!pool) {
    const notification = memory.notifications.find((entry) => entry.id === notificationId && entry.userId === userId);
    if (!notification) return false;
    notification.readAt ??= new Date().toISOString();
    return true;
  }
  const result = await pool.query(
    'UPDATE notifications SET read_at = NOW() WHERE id = $1 AND user_id = $2',
    [notificationId, userId]
  );
  return result.rowCount > 0;
}

