export async function updateOrderStatus(id, status) {
  if (!pool) {
    const order = memory.orders.find((item) => item.id === id);
    if (!order) return { error: 'Không tìm thấy đơn hàng.', status: 404 };
    if (order.status !== status && order.status === 'Đã hủy') {
      const unavailable = order.items.find((item) => memory.products.find((product) => product.id === item.id).stock < item.quantity);
      if (unavailable) return { error: `Không đủ tồn kho để khôi phục đơn #${order.id}.`, status: 409 };
      order.items.forEach((item) => { memory.products.find((product) => product.id === item.id).stock -= item.quantity; });
    }
    if (order.status !== status && status === 'Đã hủy') {
      order.items.forEach((item) => { memory.products.find((product) => product.id === item.id).stock += item.quantity; });
    }
    order.status = status;
    return { order };
  }

  return transaction(async (client) => {
    const orderResult = await client.query('SELECT * FROM orders WHERE id = $1 FOR UPDATE', [id]);
    if (!orderResult.rows[0]) return { error: 'Không tìm thấy đơn hàng.', status: 404 };
    const orderRow = orderResult.rows[0];
    const itemResult = await client.query('SELECT * FROM order_items WHERE order_id = $1 ORDER BY id', [id]);
    const items = itemResult.rows.map((item) => ({
      id: Number(item.product_id),
      name: item.product_name,
      price: Number(item.unit_price),
      quantity: item.quantity
    }));
    if (orderRow.status !== status && orderRow.status === 'Đã hủy') {
      for (const item of items) {
        const result = await client.query('SELECT stock FROM products WHERE id = $1 FOR UPDATE', [item.id]);
        if (result.rows[0].stock < item.quantity) {
          return { error: `Không đủ tồn kho để khôi phục đơn #${id}.`, status: 409 };
        }
      }
      for (const item of items) await client.query('UPDATE products SET stock = stock - $1 WHERE id = $2', [item.quantity, item.id]);
    }
    if (orderRow.status !== status && status === 'Đã hủy') {
      for (const item of items) await client.query('UPDATE products SET stock = stock + $1 WHERE id = $2', [item.quantity, item.id]);
    }
    const updated = await client.query('UPDATE orders SET status = $1 WHERE id = $2 RETURNING *', [status, id]);
    return { order: mapOrder(updated.rows[0], items) };
  });
}

