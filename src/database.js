export async function createUser(user) {
  if (!pool) {
    if (memory.users.some((item) => item.email === user.email)) return null;
    const created = { phone: '', address: '', createdAt: new Date().toISOString(), ...user, id: memory.users.length + 1 };
    memory.users.push(created);
    if (created.role === 'user') await createWelcomeBenefits(created.id);
    return created;
  }
  try {
    const result = await pool.query(
      'INSERT INTO users (name, email, role, password_hash) VALUES ($1, $2, $3, $4) RETURNING *',
      [user.name, user.email, user.role, user.passwordHash]
    );
    if (user.role === 'user') await createWelcomeBenefits(Number(result.rows[0].id));
    return mapUser(result.rows[0]);
  } catch (error) {
    if (error.code === '23505') return null;
    throw error;
  }
}

export async function createAdminAccount(user) {
  if (!pool) {
    const existing = memory.users.find((entry) => entry.email === user.email);
    if (existing) {
      Object.assign(existing, user, { role: 'admin' });
      return mapUser(existing);
    }
    const created = { ...user, role: 'admin', id: memory.users.length + 1, createdAt: new Date().toISOString() };
    memory.users.push(created);
    return mapUser(created);
  }
  const result = await pool.query(
    `INSERT INTO users (name, email, role, password_hash)
     VALUES ($1, $2, 'admin', $3)
     ON CONFLICT (email) DO UPDATE
       SET name = EXCLUDED.name, role = 'admin', password_hash = EXCLUDED.password_hash
     RETURNING *`,
    [user.name, user.email, user.passwordHash]
  );
  return mapUser(result.rows[0]);
}

export async function findUserByEmail(email) {
  if (!pool) return memory.users.find((user) => user.email === email) ?? null;
  const result = await pool.query('SELECT * FROM users WHERE email = $1', [email]);
  return result.rows[0] ? mapUser(result.rows[0]) : null;
}

export async function createSession(token, userId) {
  const expiresAt = Date.now() + 8 * 60 * 60 * 1000;
  if (!pool) {
    memory.sessions.set(token, { userId, expiresAt });
    return;
  }
  const tokenHash = createHash('sha256').update(token).digest('hex');
  await pool.query(
    `INSERT INTO sessions (token_hash, user_id, expires_at)
     VALUES ($1, $2, $3)`,
    [tokenHash, userId, new Date(expiresAt)]
  );
}

export async function getSessionUser(token) {
  if (!pool) {
    const session = memory.sessions.get(token);
    if (!session || session.expiresAt < Date.now()) {
      if (token) memory.sessions.delete(token);
      return null;
    }
    return memory.users.find((user) => user.id === session.userId) ?? null;
  }
  const tokenHash = createHash('sha256').update(token).digest('hex');
  const result = await pool.query(
    `SELECT u.* FROM sessions s
     JOIN users u ON u.id = s.user_id
     WHERE s.token_hash = $1 AND s.expires_at > NOW()`,
    [tokenHash]
  );
  return result.rows[0] ? mapUser(result.rows[0]) : null;
}

export async function deleteSession(token) {
  if (!pool) {
    memory.sessions.delete(token);
    return;
  }
  const tokenHash = createHash('sha256').update(token).digest('hex');
  await pool.query('DELETE FROM sessions WHERE token_hash = $1', [tokenHash]);
}

export async function closeDatabase() {
  if (pool) await pool.end();
}
